"""Generate config/connections.yaml from the stdio MCP servers in an agent config.yaml.

Remote (url:) servers stay direct in the upstream agent; only local stdio children move to the Switchboard.
Usage: python3 tools/import_hermes.py /path/to/config.yaml config/connections.yaml
       python3 tools/import_hermes.py /path/to/config.yaml config/connections.yaml --serialize browser,playwright
       python3 tools/import_hermes.py /path/to/config.yaml config/connections.yaml --env-file config/example.env
"""
import argparse
import sys
import yaml

ap = argparse.ArgumentParser()
ap.add_argument("src")
ap.add_argument("dst")
ap.add_argument("--serialize", default="", help="Comma-separated connector names that need serialize: true")
ap.add_argument("--env-file", default="example.env", help="env_files entry written into connections.yaml (relative to dst dir)")
args = ap.parse_args()
serialize = {s.strip() for s in args.serialize.split(",") if s.strip()}

servers = yaml.safe_load(open(args.src)).get("mcp_servers", {})
out = {}
for name, cfg in servers.items():
    if "command" not in cfg or cfg.get("enabled") is False:
        continue
    c = {"command": cfg["command"], "args": cfg.get("args", [])}
    if cfg.get("env"):
        c["env"] = {k: "" if v is None else str(v) for k, v in cfg["env"].items()}
    if cfg.get("cwd"):
        c["cwd"] = cfg["cwd"]
    if cfg.get("connect_timeout"):
        c["connect_timeout"] = cfg["connect_timeout"]
    if name in serialize:
        c["serialize"] = True
    out[name] = c
with open(args.dst, "w") as f:
    f.write("# Generated by tools/import_hermes.py; edit freely afterwards.\n")
    yaml.safe_dump({"env_files": [args.env_file], "connections": out}, f, sort_keys=False, default_flow_style=False, width=1000)
print(f"{len(out)} connections -> {args.dst}: {', '.join(out)}")
